import {
  BadRequestException,
  ConflictException,
  Injectable,
  Logger,
  ServiceUnavailableException,
} from "@nestjs/common";
import { createHash } from "node:crypto";
import { DataSource } from "typeorm";
import { withScopedDb, getActiveScopedManager } from "../common/db/scoped-db";
import { returnedRows } from "../common/db/query-result";
import {
  JobClaimService,
  JobClaimType,
} from "../common/jobs/job-claim.service";
import { tr } from "../i18n/translate";
import { SimplefinCredentialsService } from "./simplefin-credentials.service";
import {
  SimplefinClient,
  SimplefinNotDispatchedError,
} from "./providers/simplefin/simplefin.client";
import { simplefinClaimUrl } from "./providers/simplefin/simplefin.urls";

export const SIMPLEFIN_SETUP_LEASE_MS = 120_000;
export const SIMPLEFIN_SETUP_LEASE_KEY = "setup";

/** Claim and commit credentials only; discovery is a separate recoverable read. */
@Injectable()
export class SimplefinSetupService {
  private readonly logger = new Logger(SimplefinSetupService.name);
  constructor(
    private readonly dataSource: DataSource,
    private readonly claims: JobClaimService,
    private readonly credentials: SimplefinCredentialsService,
    private readonly client: SimplefinClient,
  ) {}

  /** Local removal shares setup's lease so it cannot race a token claim. */
  async disconnect(userId: string): Promise<void> {
    if (getActiveScopedManager())
      throw new Error(
        "Remove SimpleFIN outside an active database transaction",
      );
    const lease = await this.claims.claimLease(
      JobClaimType.SimplefinSetup,
      userId,
      SIMPLEFIN_SETUP_LEASE_KEY,
      SIMPLEFIN_SETUP_LEASE_MS,
    );
    if (!lease)
      throw new ConflictException(
        tr(
          "errors.bankSync.simplefinSetupRunning",
          "A SimpleFIN setup is already running. Wait for it to finish before trying again.",
        ),
      );
    try {
      await withScopedDb(this.dataSource, async (m) => {
        const rows = returnedRows(
          await m.query(
            `SELECT id FROM job_claims WHERE claim_type=$1 AND user_id=$2 AND claim_key=$3
             AND lease_token=$4::uuid AND expires_at > clock_timestamp() FOR UPDATE`,
            [
              JobClaimType.SimplefinSetup,
              userId,
              SIMPLEFIN_SETUP_LEASE_KEY,
              lease,
            ],
          ),
        );
        if (!rows.length)
          throw new ConflictException(
            tr(
              "errors.bankSync.simplefinSetupRunning",
              "A SimpleFIN setup is already running. Wait for it to finish before trying again.",
            ),
          );
        await this.credentials.remove(userId);
      });
    } finally {
      try {
        await this.claims.releaseLease(
          JobClaimType.SimplefinSetup,
          userId,
          SIMPLEFIN_SETUP_LEASE_KEY,
          lease,
        );
      } catch {
        this.logger.warn(
          "SimpleFIN setup lease cleanup failed; expiry will release it",
        );
      }
    }
  }

  async connect(
    userId: string,
    setupToken: string,
    replaceExisting = false,
  ): Promise<void> {
    if (getActiveScopedManager())
      throw new Error(
        "Claim SimpleFIN tokens outside an active database transaction",
      );
    let claimUrl: URL;
    try {
      claimUrl = simplefinClaimUrl(setupToken);
    } catch {
      throw new BadRequestException(
        tr(
          "errors.bankSync.simplefinSetupInvalid",
          "Paste a valid setup token generated by SimpleFIN Bridge.",
        ),
      );
    }
    const lease = await this.claims.claimLease(
      JobClaimType.SimplefinSetup,
      userId,
      SIMPLEFIN_SETUP_LEASE_KEY,
      SIMPLEFIN_SETUP_LEASE_MS,
    );
    if (!lease)
      throw new ConflictException(
        tr(
          "errors.bankSync.simplefinSetupRunning",
          "A SimpleFIN setup is already running. Wait for it to finish before trying again.",
        ),
      );
    try {
      const status = await this.credentials.status(userId);
      if (!status.encryptionAvailable)
        throw new BadRequestException(
          tr(
            "errors.bankSync.simplefinEncryptionRequired",
            "This server cannot store SimpleFIN credentials. Ask an administrator to configure ENCRYPTION_KEY.",
          ),
        );
      if (status.credentialSet && !replaceExisting)
        throw new ConflictException(
          tr(
            "errors.bankSync.simplefinReplaceRequired",
            "Confirm replacement of the existing SimpleFIN connection before connecting again.",
          ),
        );
      // This is an attempt marker, NOT evidence of successful credential creation.
      // It deliberately remains after any outcome, including an ambiguous timeout.
      const attemptKey =
        "token:" + createHash("sha256").update(claimUrl.href).digest("hex");
      const firstAttempt = await this.claims.claimOnce(
        JobClaimType.SimplefinSetup,
        userId,
        attemptKey,
      );
      if (!firstAttempt)
        throw new ConflictException(
          tr(
            "errors.bankSync.simplefinSetupAttempted",
            "This setup token was already attempted. Retry discovery if connected, or generate a new token in SimpleFIN Bridge.",
          ),
        );
      let accessUrl: string;
      try {
        accessUrl = await this.client.claim(setupToken);
      } catch (error) {
        if (error instanceof SimplefinNotDispatchedError) {
          // Same lock/order as credential storage. An expired worker cannot
          // remove the permanent fence after a newer worker acquired the lease.
          await withScopedDb(this.dataSource, async (m) => {
            const current = returnedRows(
              await m.query(
                `SELECT id FROM job_claims WHERE claim_type=$1 AND user_id=$2 AND claim_key=$3
               AND lease_token=$4::uuid AND expires_at > clock_timestamp() FOR UPDATE`,
                [
                  JobClaimType.SimplefinSetup,
                  userId,
                  SIMPLEFIN_SETUP_LEASE_KEY,
                  lease,
                ],
              ),
            );
            if (current.length)
              await m.query(
                "DELETE FROM job_claims WHERE claim_type=$1 AND user_id=$2 AND claim_key=$3",
                [JobClaimType.SimplefinSetup, userId, attemptKey],
              );
          });
          throw new ServiceUnavailableException(
            tr(
              "errors.bankSync.simplefinClaimNotSent",
              "SimpleFIN is temporarily unavailable. The setup token was not sent; try this token again later.",
            ),
          );
        }
        throw new ServiceUnavailableException(
          tr(
            "errors.bankSync.simplefinClaimUncertain",
            "SimpleFIN setup did not complete. The token may have been consumed. Check Bridge, revoke any unused app token, and generate a new setup token.",
          ),
        );
      }
      try {
        await withScopedDb(this.dataSource, async (m) => {
          // Lock the current lease before storing. A delayed former holder can
          // neither overwrite a newer credential nor release the newer lease.
          const rows = returnedRows(
            await m.query(
              `SELECT id FROM job_claims
              WHERE claim_type=$1 AND user_id=$2 AND claim_key=$3
                AND lease_token=$4::uuid AND expires_at > clock_timestamp()
              FOR UPDATE`,
              [
                JobClaimType.SimplefinSetup,
                userId,
                SIMPLEFIN_SETUP_LEASE_KEY,
                lease,
              ],
            ),
          );
          if (!rows.length) throw new Error("SimpleFIN setup lease expired");
          await this.credentials.storeClaimedAccessUrl(
            userId,
            accessUrl,
            replaceExisting,
          );
        });
      } catch {
        throw new ServiceUnavailableException(
          tr(
            "errors.bankSync.simplefinClaimStorageFailed",
            "SimpleFIN consumed the setup token, but Monize could not confirm saving the credential. Check connection status first. If not connected, revoke the app token in Bridge and generate a new setup token.",
          ),
        );
      }
    } finally {
      try {
        await this.claims.releaseLease(
          JobClaimType.SimplefinSetup,
          userId,
          SIMPLEFIN_SETUP_LEASE_KEY,
          lease,
        );
      } catch {
        // Expiry provides recovery. Never expose an exception that may carry SQL
        // parameters, or mask the claim's known/unknown outcome with cleanup.
        this.logger.warn(
          "SimpleFIN setup lease cleanup failed; expiry will release it",
        );
      }
    }
  }
}
